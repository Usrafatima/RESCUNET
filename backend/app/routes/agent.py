@router.get(
    "/recommendation/{incident_id}",
    summary="Get AI recommendation for an incident",
    response_description="Enriched recommendation with resource validation",
)
def get_recommendation_endpoint(incident_id: str):
    """Get enriched recommendation for an incident.

    Returns:
    - Recommended resource with capabilities, match score, distance
    - Resource availability validation
    - Agent activity timeline
    - Resource rankings
    
    Returns 404 if the incident does not exist.
    """
    # Verify incident exists
    incident = incident_service.get_incident(incident_id)
    if not incident:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Incident '{incident_id}' not found",
        )

    result = get_recommendation(incident_id)
    if result is None:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to generate recommendation",
        )
    return result


@router.post(
    "/approve/{incident_id}",
    summary="Approve an AI recommendation and create a response plan",
    response_description="Response plan with assigned resource",
)
def approve_recommendation_endpoint(incident_id: str, request: ApprovalRequest):
    """Approve a Strands agent recommendation and create a response plan.

    The endpoint will:
    1. Verify the incident exists
    2. Verify the recommended resource exists and is available
    3. Create a response plan linking incident to resource
    4. Assign the resource (update status)
    5. Return the response plan

    This does NOT perform real-world dispatch.
    The response clearly states that no real dispatch occurred.

    Returns 404 if incident or resource not found.
    Returns 409 if resource is unavailable, or if a newer rescue-plan
    proposal is pending review (stale recommendation guard).
    """
    try:
        result = approval_service.approve_recommendation(incident_id, request)
    except approval_service.StaleRecommendationError as exc:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=str(exc),
        )

    if result is None:
        # Distinguish between incident not found and resource issues
        incident = incident_service.get_incident(incident_id)
        if not incident:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Incident '{incident_id}' not found",
            )
        # Resource issue
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=f"Cannot approve: resource '{request.resource_id}' not found or unavailable",
        )

    return result

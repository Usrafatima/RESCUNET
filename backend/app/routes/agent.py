"""
FastAPI route handler for RescuNet AI Agent endpoints.

POST /api/agent/analyze/{incident_id} — invoke Strands agent
POST /api/agent/approve/{incident_id} — approve recommendation
"""

import logging

from fastapi import APIRouter, HTTPException, status

from agent.rescuenet_agent import (
    ModelRateLimitedException,
    ModelUnavailableException,
    analyze_incident,
    analyze_priority,
)
from app.models.response_plan import ApprovalRequest
from app.services import approval_service, incident_service
from app.services.recommendation_service import get_recommendation

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/agent", tags=["agent"])


@router.post(
    "/analyze/{incident_id}",
    summary="Analyze an incident with the AI agent",
    response_description="Agent recommendation with classification and resource matching",
)
def analyze_incident_endpoint(incident_id: str):
    """Invoke the RescuNet Strands Agent to analyze an incident.

    The agent will:
    1. Retrieve the incident from the database
    2. Classify the emergency type and priority
    3. Find available community resources
    4. Match the best resource to the incident
    5. Provide a recommendation requiring human approval

    Returns 404 if the incident does not exist.
    Returns 503 if the Gemini model is experiencing high demand / unavailable.
    Returns 429 if the Gemini rate limit or quota is exceeded.
    Returns 500 only for genuine agent failures.
    """
    # Verify incident exists
    incident = incident_service.get_incident(incident_id)
    if not incident:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Incident '{incident_id}' not found",
        )

    # Run agent analysis
    try:
        result = analyze_incident(incident_id)
        if result is None:
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="Agent analysis failed. Check agent configuration and logs.",
            )
        # The response now always has: incident_id, analysis, status,
        # human_approval_required, and recommendation (structured or null)
        return result
    except ModelUnavailableException as e:
        logger.warning(f"Gemini model unavailable during analysis for {incident_id}: {e}")
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=e.message,
        )
    except ModelRateLimitedException as e:
        logger.warning(f"Gemini rate limit exceeded during analysis for {incident_id}: {e}")
        raise HTTPException(
            status_code=status.HTTP_429_TOO_MANY_REQUESTS,
            detail=e.message,
        )
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Unexpected error in agent analysis for {incident_id}: {e}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="An unexpected error occurred during agent analysis",
        )



"""
Pydantic models for RescuNet agent responses.

These models define the structured output format for agent analysis.
When used as structured_output_model with Strands, the agent calls
a StructuredOutputTool as its final step, which validates against
these models — no fragile text parsing required.
"""

from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field


class IncidentType(str, Enum):
    """Classification of emergency incidents."""

    medical = "medical"
    rescue = "rescue"
    fire = "fire"
    supplies = "supplies"
    shelter = "shelter"
    infrastructure = "infrastructure"
    other = "other"


class Priority(str, Enum):
    """Incident priority levels."""

    critical = "critical"
    high = "high"
    medium = "medium"
    low = "low"


class Classification(BaseModel):
    """How the agent classified the incident."""

    type: IncidentType = Field(description="Type of emergency")
    priority: Priority = Field(description="Urgency level")
    people_affected: int = Field(description="Number of people affected")
    immediate_need: str = Field(description="Most urgent need for this incident")


class RecommendedAction(BaseModel):
    """The agent's recommended response."""

    resource_id: str = Field(description="ID of the recommended resource (e.g. RES-001)")
    resource_name: str = Field(description="Name of the recommended resource")
    resource_type: str = Field(description="Type of the resource (medical, rescue, etc.)")
    reason: str = Field(description="Why this resource was selected")
    distance_km: float = Field(description="Distance from incident to resource in km")


class AgentRecommendation(BaseModel):
    """Complete agent analysis and recommendation.

    This model is used as Strands' structured_output_model.
    The agent must call the StructuredOutputTool with all these fields
    as its final action, guaranteeing valid structured output.
    """

    incident_id: str = Field(description="ID of the analyzed incident")
    analysis: str = Field(description="Human-readable analysis of the incident and reasoning")
    classification: Classification = Field(description="Incident classification")
    recommended_action: RecommendedAction = Field(description="Recommended response")
    human_approval_required: bool = Field(
        default=True,
        description="Whether human approval is needed before dispatch",
    )


class AgentAnalysisResponse(BaseModel):
    """API response for agent analysis endpoint."""

    incident_id: str
    status: str = "recommendation_ready"
    recommendation: AgentRecommendation
    human_approval_required: bool = True


class ResourceStatus(str, Enum):
    """Resource availability status."""

    available = "available"
    dispatched = "dispatched"
    unavailable = "unavailable"


# ─── Priority Queue Models ──────────────────────────────────────────────


class PriorityFactors(BaseModel):
    """Structured factors extracted by the AI for priority scoring.

    Each factor is 0-100. The AI provides these as input;
    the final score is calculated deterministically in backend code.
    """

    severity: int = Field(
        ge=0, le=100,
        description="Severity/urgency of the emergency (0-100)",
    )
    people_affected: int = Field(
        ge=0, le=100,
        description="Scaled impact by number of people (0-100)",
    )
    urgency: int = Field(
        ge=0, le=100,
        description="Time-sensitivity / immediate threat to life (0-100)",
    )
    resource_need: int = Field(
        ge=0, le=100,
        description="Specialized resource requirement (0-100)",
    )
    reason: str = Field(
        description="Human-readable explanation for the priority assessment",
    )


class PriorityAnalysisResult(BaseModel):
    """AI-generated priority analysis for a single incident.

    This is the structured output from the LLM; the final score
    is NOT generated by the LLM — it is calculated deterministically.
    """

    incident_id: str = Field(description="ID of the analyzed incident")
    priority_label: Priority = Field(description="AI-assigned priority label")
    factors: PriorityFactors = Field(description="Structured priority factors")
    recommended_resource_type: str = Field(
        description="Type of resource needed (medical, rescue, fire, etc.)",
    )


class ResourceAvailabilityInfo(BaseModel):
    """Resource availability for a priority queue item."""

    resource_id: str
    resource_name: str
    resource_type: str
    status: str  # available, deployed, unavailable
    is_suitable: bool  # whether this resource matches the incident type


class PriorityQueueItem(BaseModel):
    """A single item in the AI priority queue."""

    rank: int = Field(description="Priority rank (1 = highest)")
    incident_id: str = Field(description="Incident identifier (RSN-xxxxxx or EDGE-xxxxxx)")
    description: str = Field(description="Incident description")
    incident_type: str = Field(description="Classified incident type")
    priority_label: str = Field(description="Priority level: critical, high, medium, low")
    score: float = Field(description="Deterministic priority score (0-100)")
    people_affected: int = Field(description="Number of people affected")
    waiting_time_seconds: float = Field(description="How long the incident has been waiting")
    waiting_time_display: str = Field(description="Human-readable waiting time")
    recommended_resource: ResourceAvailabilityInfo = Field(
        description="Best available resource for this incident",
    )
    factors: PriorityFactors = Field(description="AI-extracted priority factors")
    reason: str = Field(description="Why this incident has this priority")


class PriorityQueueResponse(BaseModel):
    """Response for the priority queue endpoint."""

    queue: list[PriorityQueueItem] = Field(description="Sorted priority queue")
    total_active: int = Field(description="Total number of active incidents")
    generated_at: str = Field(description="ISO timestamp of queue generation")
    scoring_weights: dict[str, float] = Field(
        description="Current scoring weights for transparency",
    )
